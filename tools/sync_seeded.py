"""Generate src/prophet_batch/_seeded.py from the fork's forecaster.py.

The package runs on stock Prophet, whose predict has no `rng` or `history_uncertainty`. The fork (prophet-dev)
threads an rng through the sampling chain; this script copies those methods verbatim into a mixin class, so the
package's seeded predict is the fork's code, line for line. Regressor predictors (stock Prophet objects) are routed
through the same mixin. Re-run after changing the fork, then run the package tests:

    uv run python prophet-batch/tools/sync_seeded.py [path/to/forecaster.py]   # from the workspace
    uv run python prophet-batch/tools/sync_seeded.py --check   # exit 1 if _seeded.py is out of date
"""

import ast
import sys
from pathlib import Path

# The parallel-prophet workspace this repo is cloned into, next to prophet-dev.
ROOT = Path(__file__).resolve().parents[2]
FORK = ROOT / 'prophet-dev' / 'python' / 'prophet' / 'forecaster.py'
OUT = Path(__file__).parents[1] / 'src' / 'prophet_batch' / '_seeded.py'

METHODS = [
    'predict',
    '_prepare_regressors_for_predict',
    'predict_uncertainty',
    '_future_uncertainty',
    '_analytic_history_intervals',
    '_order_statistic_history_intervals',
    '_norm_ppf',
    'sample_posterior_predictive',
    'sample_model',
    'sample_model_vectorized',
    'sample_predictive_trend',
    'sample_predictive_trend_vectorized',
    '_sample_uncertainty',
    '_make_trend_shift_matrix',
    '_logistic_uncertainty',
    'predictive_samples',
    '_percentile_skip_constant_rows',
]

# The only edits to the copied code: regressor predictors are stock Prophet objects, so they get a seeded view.
REPLACE = [
    ('predictor.predict(reg_future, **rng_kw)', 'seeded(predictor).predict(reg_future, **rng_kw)'),
    ('predictor.predictive_samples(reg_future, **rng_kw)',
     'seeded(predictor).predictive_samples(reg_future, **rng_kw)'),
]

HEADER = '''\
# Copyright (c) Facebook, Inc. and its affiliates.

# This source code is licensed under the MIT license found in the
# LICENSE file in the root directory of this source tree.

# GENERATED by tools/sync_seeded.py from the prophet-dev fork's forecaster.py
# ({source}). Do not edit by hand: change the fork and re-run the script.

"""Seeded predict for stock Prophet models.

`seeded(model)` returns a shallow view of a fitted Prophet model whose class
adds the fork's rng-aware sampling methods (predict(rng=, history_uncertainty=)
and the methods it calls) on top of the model's own class. Prophet itself is not
modified; with rng=None and history_uncertainty=True the view's predict is
bit-identical to the stock predict.
"""

from __future__ import annotations

import copy
import logging
from statistics import NormalDist
from typing import TYPE_CHECKING, Any, Literal, cast

import numpy as np
import numpy.typing as npt
import pandas as pd

if TYPE_CHECKING:
    from prophet import Prophet

logger: logging.Logger = logging.getLogger('prophet')  # same messages as stock predict


def _random(rng: np.random.Generator | None) -> Any:
    """The source of random draws: the given Generator, or NumPy's global RNG (default)."""
    return np.random if rng is None else rng


class _SeededSampling:
    """The fork's rng-aware predict and sampling methods (mixed into a Prophet subclass)."""

    # Attributes provided by the Prophet class this is mixed into.
    history: Any
    params: Any
    uncertainty_samples: int
    interval_width: float
    mcmc_samples: int
    y_scale: Any
    extra_regressors: Any
    changepoints_t: Any
    growth: str
    logistic_floor: bool
    setup_dataframe: Any
    predict_trend: Any
    predict_seasonal_components: Any
    make_all_seasonality_features: Any
    piecewise_linear: Any
    piecewise_logistic: Any
    flat_trend: Any
    percentile: Any
    _make_historical_mat_time: Any

'''

FOOTER = '''

_CLASSES: dict[type, type] = {}


def seeded(model: Prophet) -> Any:
    """A shallow view of `model` whose predict accepts rng= and history_uncertainty=.

    Parameters
    ----------
    model: A fitted Prophet model (stock or a subclass).

    Returns
    -------
    A shallow copy of the model (sharing its fitted state) of a subclass that adds
    the seeded sampling methods.
    """
    cls = type(model)
    if issubclass(cls, _SeededSampling):
        return model
    if cls not in _CLASSES:
        _CLASSES[cls] = type('Seeded' + cls.__name__, (_SeededSampling, cls), {})
    view = copy.copy(model)
    view.__class__ = _CLASSES[cls]
    return view
'''


def method_source(lines, node):
    start = min([d.lineno for d in node.decorator_list] + [node.lineno]) - 1
    return ''.join(lines[start:node.end_lineno])


def main():
    args = [a for a in sys.argv[1:] if a != '--check']
    check = '--check' in sys.argv[1:]
    fork = Path(args[0]) if args else FORK
    text = fork.read_text(encoding='utf-8')
    lines = text.splitlines(keepends=True)
    cls = next(n for n in ast.parse(text).body if isinstance(n, ast.ClassDef) and n.name == 'Prophet')
    found = {n.name: n for n in cls.body if isinstance(n, ast.FunctionDef)}
    missing = [m for m in METHODS if m not in found]
    if missing:
        raise SystemExit(f'not in {fork}: {missing}')
    body = '\n'.join(method_source(lines, found[m]) for m in METHODS)
    for old, new in REPLACE:
        if body.count(old) != 1:
            raise SystemExit(f'expected exactly one {old!r} in the copied methods')
        body = body.replace(old, new)
    try:
        source = fork.relative_to(ROOT)
    except ValueError:
        source = fork
    text = HEADER.format(source=source) + body + FOOTER
    if check:
        if OUT.read_text(encoding='utf-8') != text:
            raise SystemExit(f'{OUT} is out of date with {fork}: re-run tools/sync_seeded.py')
        print(f'{OUT.name} is up to date with {fork}')
        return
    OUT.write_text(text, encoding='utf-8')
    print(f'wrote {OUT} ({len(METHODS)} methods from {fork})')


if __name__ == '__main__':
    main()
